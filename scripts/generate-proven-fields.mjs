#!/usr/bin/env node
/**
 * generate-proven-fields.mjs — build the render gate's source of truth.
 *
 * Reads scripts/validate/reports/proof-latest.json (the proof engine's computed
 * output) and emits src/data/proven-fields.ts: a per-council set of the field paths
 * that are PROVEN. The UI's `isProven()` consults this so a number renders ONLY if
 * the proof engine could re-derive it from evidence (Stage 5 default-deny).
 *
 * This mirrors the existing generate-coverage-stats.mjs pattern — proof can't run at
 * request time (needs pdftotext + file reads), so we bake its verdict into a build
 * artifact the UI imports.
 *
 * Run: node scripts/generate-proven-fields.mjs   (or npm run generate:proven)
 * CI/regen: run after every proof run; the file is committed so deploys are gated.
 */

import { readFileSync, writeFileSync, existsSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPORT = join(__dirname, 'validate', 'reports', 'proof-latest.json');
const OUT = join(__dirname, '..', 'src', 'data', 'proven-fields.ts');

const BAND_D_YEARS = ['band_d_2021', 'band_d_2022', 'band_d_2023', 'band_d_2024', 'band_d_2025', 'band_d_2026'];

// MUST match generateSlug() in src/data/councils.ts EXACTLY — the gate keys on the
// same slug the UI routes on, or a council would silently un-gate. (Note: strips
// apostrophes FIRST, unlike proof.mjs's slugify, which is why we re-derive from name.)
function uiSlug(name) {
  return name
    .toLowerCase()
    .replace(/['']/g, '')
    .replace(/&/g, 'and')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .replace(/-+/g, '-');
}

const header = `/**
 * Auto-generated by scripts/generate-proven-fields.mjs
 * Source: scripts/validate/reports/proof-latest.json
 *
 * DO NOT EDIT MANUALLY — run: npm run generate:proven
 *
 * The render gate's source of truth (NORTH-STAR / PIPELINE.md Stage 5).
 * PROVEN_FIELDS[councilSlug] = the set of field paths the proof engine could
 * independently re-derive from evidence. A value renders ONLY if it is in this
 * set (default-deny): unproven numbers are hidden, never shown wrong.
 */
`;

if (!existsSync(REPORT)) {
  // Fail-safe: no proof report (e.g. fresh checkout before first proof run).
  // Emit an EMPTY map. With default-deny + empty map the gate would hide
  // everything — so the UI's isProven() treats an empty/missing map as
  // "gate disabled" (see proven-fields helper) to avoid blanking the site
  // on a runner that simply hasn't generated the artifact. The committed
  // file (generated where data exists) is what actually gates production.
  const empty = `${header}
export const PROVEN_FIELDS: Record<string, string[]> = {};
export const PROVEN_GENERATED_AT: string | null = null;
`;
  writeFileSync(OUT, empty);
  console.log('generate-proven-fields: no proof-latest.json — wrote empty map (gate inert until proof runs).');
  process.exit(0);
}

const report = JSON.parse(readFileSync(REPORT, 'utf8'));
const proven = {};

for (const c of report.councils || []) {
  const fields = new Set();

  // Tier-3 proven entries (council-PDF + national-CSV lanes that passed every invariant).
  for (const e of c.tier3?.entries || []) {
    if (String(e.verdict).startsWith('PROVEN')) fields.add(`detailed.${e.field}`);
  }

  // Band D council tax: proven when the council is Tier-1 safe (every present year
  // byte-exact vs the GOV.UK CSV, checked in proof's Tier-1 block).
  if (c.tier1_safe) {
    for (const y of BAND_D_YEARS) fields.add(`council_tax.${y}`);
  }

  // Multi-year history: each proven history entry → its year-qualified path.
  for (const h of c.history?.entries || []) {
    if (String(h.verdict).startsWith('PROVEN')) fields.add(`history.${h.field}.${h.year}`);
  }

  if (fields.size > 0) proven[uiSlug(c.name)] = [...fields].sort();
}

const body = `${header}
export const PROVEN_FIELDS: Record<string, string[]> = ${JSON.stringify(proven, null, 2)};

export const PROVEN_GENERATED_AT = ${JSON.stringify(report.generated || report.timestamp || report.summary?.timestamp || 'unknown')};
`;

writeFileSync(OUT, body);
const councilCount = Object.keys(proven).length;
const fieldCount = Object.values(proven).reduce((a, f) => a + f.length, 0);
console.log(`generate-proven-fields: ${fieldCount} proven fields across ${councilCount} councils → src/data/proven-fields.ts`);
